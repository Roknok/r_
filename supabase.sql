-- Run this in the Supabase SQL Editor.
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 2 and 18),
  score integer not null check (score >= 0 and score <= 100000000),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

drop policy if exists "Scores are visible to everyone" on public.scores;
create policy "Scores are visible to everyone"
on public.scores for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can submit a score" on public.scores;
create policy "Anyone can submit a score"
on public.scores for insert
to anon, authenticated
with check (
  char_length(player_name) between 2 and 18
  and score >= 0
  and score <= 100000000
);

-- No update/delete policies are created for public users.


-- Explicit API privileges: RLS policies alone do not grant table access.
grant usage on schema public to anon, authenticated;
grant select, insert on table public.scores to anon, authenticated;
grant usage, select on sequence public.scores_id_seq to anon, authenticated;
